"""Base comun de los modelos de tabla (C-03, D2 y D3).

Al importarse fija la convencion de nombres de restricciones e indices sobre
``SQLModel.metadata``: cada ``models.py`` de modulo importa este modulo
PRIMERO, antes de declarar tablas. La metadata propia de los modelos de prueba
(``BasePrueba``) es otra instancia y no recibe la convencion.

Los helpers devuelven un ``Field`` con una ``Column`` NUEVA en cada llamada
(una ``Column`` no puede compartirse entre tablas) y nunca usan ``AutoString``/
``VARCHAR``: texto es ``TEXT``, fecha es ``TIMESTAMPTZ``, dinero es ``NUMERIC``
(``Decimal``), clave primaria es ``BIGINT`` con identidad.
"""
from datetime import UTC, datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    DateTime,
    ForeignKey,
    Identity,
    Integer,
    Numeric,
    Text,
    text,
)
from sqlmodel import Field, SQLModel

__all__ = [
    "CONVENCION_NOMBRES",
    "booleano",
    "dinero",
    "entero",
    "fecha",
    "fk",
    "pk_identidad",
    "texto",
]

CONVENCION_NOMBRES = {
    "ix": "ix_%(column_0_N_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

SQLModel.metadata.naming_convention = CONVENCION_NOMBRES


def pk_identidad() -> Any:
    """``id BIGINT GENERATED BY DEFAULT AS IDENTITY`` (admite ids explicitos en el seed)."""
    return Field(
        default=None,
        sa_column=Column(BigInteger, Identity(always=False), primary_key=True),
    )


def fk(destino: str, *, nullable: bool = False, tipo: Any = BigInteger, index: bool = False) -> Any:
    """Clave foranea a ``tabla.columna``; sin ``ON DELETE`` (``NO ACTION``).

    ``index=True`` crea el indice propio; omitirlo cuando una restriccion UNIQUE
    ya cubre la columna como primer campo.
    """
    columna = Column(tipo, ForeignKey(destino), nullable=nullable, index=index)
    return Field(default=None, sa_column=columna) if nullable else Field(sa_column=columna)


def fecha(*, nullable: bool = False, server_default_now: bool = False) -> Any:
    """``TIMESTAMPTZ``. Con ``server_default_now``: ``now()`` en la base y ``datetime.now(UTC)`` en Python."""
    if server_default_now:
        columna = Column(
            DateTime(timezone=True), nullable=nullable, server_default=text("now()")
        )
        return Field(default_factory=lambda: datetime.now(UTC), sa_column=columna)
    columna = Column(DateTime(timezone=True), nullable=nullable)
    return Field(default=None, sa_column=columna) if nullable else Field(sa_column=columna)


def dinero(precision: int, escala: int, *, cero_por_defecto: bool = False) -> Any:
    """``NUMERIC(precision, escala)`` leido como ``Decimal`` (nunca ``float``)."""
    tipo = Numeric(precision, escala, asdecimal=True)
    if cero_por_defecto:
        columna = Column(tipo, nullable=False, server_default=text("0"))
        return Field(default=Decimal("0"), sa_column=columna)
    return Field(sa_column=Column(tipo, nullable=False))


def texto(*, nullable: bool = False, primary_key: bool = False) -> Any:
    """``TEXT`` (no ``VARCHAR``/``AutoString``)."""
    columna = Column(Text, nullable=nullable, primary_key=primary_key)
    return Field(default=None, sa_column=columna) if nullable else Field(sa_column=columna)


def entero(*, server_default: str | None = None, default: int | None = None) -> Any:
    """``INTEGER NOT NULL`` con default opcional (de servidor y de Python)."""
    sd = text(server_default) if server_default is not None else None
    columna = Column(Integer, nullable=False, server_default=sd)
    return Field(sa_column=columna) if default is None else Field(default=default, sa_column=columna)


def booleano(*, server_default: str | None = None, default: bool | None = None) -> Any:
    """``BOOLEAN NOT NULL`` con default opcional (de servidor y de Python)."""
    sd = text(server_default) if server_default is not None else None
    columna = Column(Boolean, nullable=False, server_default=sd)
    return Field(sa_column=columna) if default is None else Field(default=default, sa_column=columna)
